// Collects Picturama and every library that ships inside a build with it, and writes them, together with their
// verbatim license texts, to the gzipped `licenses.json.gz` in the project root.
//
// Why generated and not checked in: the list is a property of the build, not of the source tree. The Debian
// package versions inside the AppImage differ between amd64 and aarch64 and change whenever the build container
// is rebuilt, and the Rust crates differ per target platform. A checked-in list would be a second source of
// truth that goes stale without anyone noticing.
//
// The license texts are harvested from the packages themselves rather than from a list of canonical texts. That
// keeps each component's own copyright line attached to its own text — which is what MIT and the BSD licenses
// ask for — and it means this script carries no license database that could drift.
//
// Run it as `npm run licenses`. That is enough for development: it collects the Rust crates and the npm
// packages, which is all the app needs to render the view.
//
// Optional parameters:
//
//     --components <path>    a JSON file holding an array of libraries the build brings in itself (a
//                            self-built libheif, the codec DLLs, the MSVC runtime) - see
//                            `collectExtraComponents` for the fields
//     --appdir <path>        a Linux AppDir, to add the system libraries linuxdeploy bundled into it
//     --out <path>           where to write (default: licenses.json.gz in the current directory)


import { execFileSync } from 'child_process'
import { createHash } from 'crypto'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'fs'
import { basename, dirname, join } from 'path'
import { gzipSync } from 'zlib'


// A file in a package directory holding a license text. Deliberately generous: packages disagree about the
// spelling, and taking one file too many costs nothing while missing one loses the text we are after.
const licenseFileRegex = /^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICEN[CS]E)/i

// Files matching the pattern above that are not license texts. `gz` is in there for `licenses.json.gz`: this
// script writes it into the very directory it scans for Picturama's own license, and reading a compressed file
// as UTF-8 would store the mojibake as a license text.
const licenseFileExcludeRegex = /\.(js|ts|json|py|rs|sh|gz)$/i


main()


function main() {
    const options = parseArgs(process.argv.slice(2))
    const texts = {}
    const own = collectPicturamaItself(texts)
    const libraries = []

    for (const library of collectRustCrates(texts)) {
        libraries.push(library)
    }
    for (const library of collectNpmPackages(texts)) {
        libraries.push(library)
    }
    for (const library of collectExtraComponents(options.components, texts)) {
        libraries.push(library)
    }
    if (options.appDir) {
        for (const library of collectSystemLibraries(options.appDir, texts)) {
            libraries.push(library)
        }
    }

    // Sorted so two runs of the same build produce byte-identical output.
    libraries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

    // A component with one license text does not need the file it came from named — the license expression it
    // declares is what the reader wants on the button. With several, the file names are what tells them apart.
    for (const component of [own, ...libraries]) {
        if (component.texts.length === 1 && component.license !== 'see copyright file') {
            component.texts[0].name = component.license
        }
    }

    const withoutText = libraries.filter(library => library.texts.length === 0)
    if (withoutText.length) {
        // Not fatal: a library without a bundled license file still has to appear in the list.
        // But it must not pass unnoticed.
        console.warn(`⚠ No license text found for ${withoutText.length} librar(y/ies): ` +
            withoutText.map(library => library.name).join(', '))
    }

    // `own` and `libraries` are separate because the dialog shows them differently — Picturama's own license
    // above, the rest as a list below. Splitting them here rather than in the UI keeps that out of the render
    // path, where it would run again on every re-render of several hundred entries.
    const result = {
        info: 'Generated by src/script/collect-licenses.mjs',
        generated: new Date().toISOString().substring(0, 10),
        texts,
        own,
        libraries,
    }
    // Gzipped: the texts are the bulk of it and compress to about a tenth, which is worth having in every
    // installer and in the AppImage. The app reads it through `fetch_licenses`, which unpacks it.
    const packed = gzipSync(Buffer.from(JSON.stringify(result)), { level: 9 })
    writeFileSync(options.out, packed)
    console.log(`${libraries.length} libraries, ${Object.keys(texts).length} distinct license texts, `
        + `${Math.round(packed.length / 1024)} KiB → ${options.out}`)
}


// Picturama's own license, so the dialog can show it from the same data as everything else instead of
// carrying a copy of the text. No version and no source URL: the version on screen comes from
// `UiConfig.version`, and a source link is what the LGPL asks for from *other* people's libraries.
function collectPicturamaItself(texts) {
    return {
        name: 'Picturama',
        license: JSON.parse(readFileSync('package.json', 'utf8')).license,
        texts: collectTextsFrom('.', texts),
    }
}


function parseArgs(argv) {
    const options = { out: 'licenses.json.gz', appDir: null, components: [] }
    for (let i = 0; i < argv.length; i++) {
        const value = argv[i + 1]
        switch (argv[i]) {
            case '--out':    options.out = requireValue(argv[i], value); i++; break
            case '--appdir': options.appDir = requireValue(argv[i], value); i++; break
            case '--components':
                options.components = JSON.parse(readFileSync(requireValue(argv[i], value), 'utf8'))
                i++
                break
            default:
                fail(`Unknown argument: ${argv[i]}`)
        }
    }
    return options
}


function requireValue(name, value) {
    if (value === undefined) {
        fail(`${name} needs a value`)
    }
    return value
}


// ── The Rust crates ──────────────────────────────────────────────────────────────────────────────

// `--filter-platform` is what makes this correct rather than merely plausible: without it the graph holds every
// crate for every target (the Windows and macOS ones too), and with it exactly the crates that this build
// compiles. It also lets the command run `--offline`, since nothing outside the platform has to be resolved.
//
// Only normal dependencies are followed. Build dependencies and dev dependencies compile on the build machine
// but do not end up in the binary, so they are not distributed and carry no obligation.
function collectRustCrates(texts) {
    const metadata = JSON.parse(execFileSync('cargo',
        ['metadata', '--format-version', '1', '--offline', '--filter-platform', hostTriple()],
        { cwd: 'src-tauri', encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 }))

    const nodesById = {}
    for (const node of metadata.resolve.nodes) {
        nodesById[node.id] = node
    }

    const root = metadata.resolve.root
    const reached = new Set()
    for (const stack = [root]; stack.length > 0; ) {
        const id = stack.pop()
        if (reached.has(id)) {
            continue
        }
        reached.add(id)
        for (const dep of nodesById[id].deps) {
            // `kind: null` is a normal dependency; "build" and "dev" are the other two.
            if (dep.dep_kinds.some(depKind => depKind.kind === null)) {
                stack.push(dep.pkg)
            }
        }
    }

    const components = []
    for (const pkg of metadata.packages) {
        if (!reached.has(pkg.id) || pkg.id === root) {
            continue
        }
        components.push({
            name: pkg.name,
            version: pkg.version,
            license: pkg.license ?? 'unknown',
            origin: 'crates.io',
            source: pkg.repository ?? undefined,
            texts: collectTextsFrom(dirname(pkg.manifest_path), texts),
        })
    }
    return components
}


function hostTriple() {
    const match = /^host: (.+)$/m.exec(execFileSync('rustc', ['-vV'], { encoding: 'utf8' }))
    if (!match) {
        fail('Could not read the host triple from `rustc -vV`')
    }
    return match[1]
}


// ── The npm packages ─────────────────────────────────────────────────────────────────────────────

// `--omit=dev` is the point: Vite bundles the runtime dependencies into the frontend and Tauri embeds that into
// the binary, while Jest, TypeScript and the Vite plugins never leave the build machine. `--parseable` gives one
// installed directory per line, which saves walking npm's nested tree to find where a package actually landed.
function collectNpmPackages(texts) {
    const output = execFileSync('npm', ['ls', '--all', '--omit=dev', '--parseable'],
        { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })

    const components = []
    for (const dir of output.split('\n')) {
        if (!dir || !dir.includes('node_modules')) {
            continue  // The first line is the project itself.
        }
        const manifestPath = join(dir, 'package.json')
        if (!existsSync(manifestPath)) {
            continue
        }
        const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
        components.push({
            name: manifest.name,
            version: manifest.version,
            license: normalizeNpmLicense(manifest),
            origin: 'npm',
            source: repositoryUrlOf(manifest),
            texts: collectTextsFrom(dir, texts),
        })
    }
    return components
}


// npm has had three spellings for this over the years. The `licenses` array is deprecated but still out there.
function normalizeNpmLicense(manifest) {
    if (typeof manifest.license === 'string') {
        return manifest.license
    } else if (manifest.license?.type) {
        return manifest.license.type
    } else if (Array.isArray(manifest.licenses)) {
        return manifest.licenses.map(entry => entry.type ?? entry).join(' OR ')
    }
    return 'unknown'
}


function repositoryUrlOf(manifest) {
    const repository = manifest.repository
    const url = typeof repository === 'string' ? repository : repository?.url
    return url ? url.replace(/^git\+/, '').replace(/\.git$/, '') : undefined
}


// ── Extra components ─────────────────────────────────────────────────────────────────────────────

// Extra components can be passed in through `--components`.
// Fields: name, version, license, source, note, and either `textFile` (a path to read) or `text` (the text itself).
function collectExtraComponents(specs, texts) {
    return specs.map(spec => {
        const text = spec.text ?? (spec.textFile ? readFileSync(spec.textFile, 'utf8') : null)
        return {
            name: spec.name,
            version: spec.version ?? '',
            license: spec.license ?? 'unknown',
            origin: spec.origin ?? 'bundled',
            source: spec.source,
            note: spec.note,
            texts: text ? [{ name: spec.license ?? 'License', key: addText(texts, text) }] : [],
        }
    })
}


// ── The system libraries inside a Linux AppDir ───────────────────────────────────────────────────

// linuxdeploy copies the Debian copyright file of every package it takes a library from into
// `usr/share/doc/<package>/copyright`, so the AppDir names its own sources — no `dpkg -S` guessing from file
// names needed. Only the version has to be asked for, and that answer comes from the machine that installed
// them, which is the build container.
//
// The copyright file is taken verbatim rather than parsed. Debian's machine-readable format assigns a license
// per file pattern, and picking "the" license out of it goes wrong in exactly the cases that matter: for
// util-linux, elfutils, colord and idn2 the `Files: *` stanza describes the command-line tools, while the
// library we ship sits in a later stanza under a different license.
function collectSystemLibraries(appDir, texts) {
    const docDir = join(appDir, 'usr', 'share', 'doc')
    if (!existsSync(docDir)) {
        fail(`${docDir} does not exist — is that an AppDir built by linuxdeploy?`)
    }

    const versions = debianPackageVersions(readdirSync(docDir))
    const components = []
    for (const pkg of readdirSync(docDir).sort()) {
        const copyrightPath = join(docDir, pkg, 'copyright')
        if (!existsSync(copyrightPath)) {
            continue
        }
        const copyright = readFileSync(copyrightPath, 'utf8')
        components.push({
            name: pkg,
            version: versions[pkg] ?? '',
            license: 'see copyright file',
            origin: 'debian',
            texts: [
                { name: 'Copyright file', key: addText(texts, copyright) },
                ...referencedCommonLicenses(copyright, texts),
            ],
        })
    }
    return components
}


// `${Package}` rather than `${binary:Package}`: the latter appends the architecture for multi-arch packages
// (`libgtk-3-0:arm64`), and what has to match is the directory name under `usr/share/doc`.
function debianPackageVersions(packages) {
    const versions = {}
    let output = ''
    try {
        output = execFileSync('dpkg-query', ['-W', '-f', '${Package} ${Version}\n', ...packages],
            { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
    } catch (error) {
        // dpkg-query exits non-zero as soon as one name is unknown, but still reports the ones it found — and
        // `usr/share/doc` holds a few directories that are not packages. Running outside the build container
        // ends up here as well, with no output at all; the list stays useful without versions.
        output = error.stdout ?? ''
    }
    for (const line of output.split('\n')) {
        const [name, version] = line.split(' ')
        if (name && version) {
            versions[name] = version
        }
    }
    if (Object.keys(versions).length === 0) {
        console.warn('⚠ dpkg-query answered nothing — system libraries will be listed without versions')
    }
    return versions
}


// Debian's copyright files do not repeat the GPL, LGPL or Apache text; they point at
// `/usr/share/common-licenses/<name>`, which is present on every Debian system and therefore not part of the
// package. Inside an AppImage that reference goes nowhere, so the texts are pulled in here.
function referencedCommonLicenses(copyright, texts) {
    const refs = []
    for (const match of copyright.matchAll(/\/usr\/share\/common-licenses\/([A-Za-z0-9.+-]*[A-Za-z0-9])/g)) {
        const path = `/usr/share/common-licenses/${match[1]}`
        if (existsSync(path)) {
            const key = addText(texts, readFileSync(path, 'utf8'))
            if (!refs.some(ref => ref.key === key)) {
                // The file names there are the license names: GPL-2, LGPL-2.1, Apache-2.0, MPL-2.0, …
                refs.push({ name: basename(path), key })
            }
        }
    }
    return refs
}


// ── License texts ────────────────────────────────────────────────────────────────────────────────

// Returns `{ name, key }` references: `name` is what the button in the license dialog says, `key` looks the
// text up. The file name is the fallback name — for a package carrying `LICENSE-MIT` and `LICENSE-APACHE`
// it is the only thing that tells the two apart. `main` replaces it with the license expression where a
// component has just the one text.
function collectTextsFrom(dir, texts) {
    const refs = []
    if (!existsSync(dir)) {
        return refs
    }
    for (const name of readdirSync(dir).sort()) {
        if (!licenseFileRegex.test(name) || licenseFileExcludeRegex.test(name)) {
            continue
        }
        const path = join(dir, name)
        if (!statSync(path).isFile()) {
            continue
        }
        const key = addText(texts, readFileSync(path, 'utf8'))
        if (!refs.some(ref => ref.key === key)) {
            refs.push({ name, key })
        }
    }
    return refs
}


// Texts are stored once and referenced by a hash of their content. That is what lets everything live in a single
// file: 450 packages share far fewer texts, and two packages under the same license with the same copyright
// holder share one entry — while an MIT text naming a different holder stays its own entry, which is the whole
// point of the notice.
function addText(texts, text) {
    const normalized = text.replace(/\r\n/g, '\n').trim()
    const key = createHash('sha256').update(normalized).digest('hex').substring(0, 12)
    texts[key] = normalized
    return key
}


function fail(message) {
    console.error(`✖ ${message}`)
    process.exit(1)
}
